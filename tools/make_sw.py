"""Regenerate sw.js (the offline cache list) after changing game files:  python3 tools/make_sw.py
The cache name is a hash of the game files, so phones pick up a new version the next time they open online."""
import hashlib, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEEP_DIRS = ['js', 'css', 'assets', 'vendor', 'icons']
files = ['index.html', 'manifest.webmanifest']
for d in KEEP_DIRS:
    for dp, _, fs in os.walk(os.path.join(ROOT, d)):
        for f in fs:
            files.append(os.path.relpath(os.path.join(dp, f), ROOT).replace(os.sep, '/'))
files.sort()
h = hashlib.sha1()
for f in files: h.update(open(os.path.join(ROOT, f), 'rb').read())
ver = h.hexdigest()[:10]
sw = '''// Tide Tossers offline cache. Generated by tools/make_sw.py; the version changes whenever a game file changes.
var CACHE = 'tide-tossers-%s';
var FILES = ['./'].concat(%s);
self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) { return c.addAll(FILES); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
// Network first (so updates arrive when online), cache when offline.
self.addEventListener('fetch', function (e) {
  if (e.request.method !== 'GET') return;
  e.respondWith(fetch(e.request).then(function (res) {
    if (res && res.ok && new URL(e.request.url).origin === location.origin) {
      var copy = res.clone(); caches.open(CACHE).then(function (c) { c.put(e.request, copy); });
    }
    return res;
  }).catch(function () { return caches.match(e.request, { ignoreSearch: true }); }));
});
''' % (ver, json.dumps(files))
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
print('sw.js version', ver, len(files), 'files')
